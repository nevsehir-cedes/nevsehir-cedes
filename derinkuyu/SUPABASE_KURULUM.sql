-- DERİNKUYU DEĞER KARTI / SUPABASE KURULUMU
-- Bu dosya Supabase SQL Editor içinde bir kez çalıştırılır.

create table if not exists public.derinkuyu_deger_karti (
  id bigint generated by default as identity primary key,
  participant_code text not null,
  school text,
  grade text,
  q1_most_impressive text not null,
  q2_values text[] not null default '{}',
  q3_helping_example text not null,
  q4_safety_measure text not null,
  q5_most_memorable_place text not null,
  q6_why_protect_heritage text not null,
  q7_key_learning text not null,
  q8_theme_reflection text not null,
  one_sentence_derinkuyu text not null,
  self_evaluation text not null,
  trip_date date not null default '2026-11-25',
  submitted_at timestamptz not null default now()
);

alter table public.derinkuyu_deger_karti enable row level security;

-- Öğrenci uygulaması yalnızca yeni cevap ekleyebilir.
drop policy if exists "anon_insert_derinkuyu_deger_karti" on public.derinkuyu_deger_karti;
create policy "anon_insert_derinkuyu_deger_karti"
on public.derinkuyu_deger_karti
for insert
to anon
with check (true);

-- Bilerek anon SELECT politikası oluşturulmuyor.
-- Sonuçların okunması Supabase panelinden veya kimlik doğrulamalı yönetici ekranından yapılmalıdır.

create index if not exists derinkuyu_deger_karti_submitted_idx
  on public.derinkuyu_deger_karti (submitted_at desc);

create index if not exists derinkuyu_deger_karti_school_idx
  on public.derinkuyu_deger_karti (school);
